import type { Action } from '../agent/actions/builder';
import { ActionBuilder } from '../agent/actions/builder';
import type { AgentContext } from '../agent/types';
import { shortDescription, TOOL_GROUPS } from '../capabilities/catalog';
import type { CapabilityGroupId } from '../capabilities/catalog';
import { registeredVoiceTools } from '../registry';
import { VOICE_TOOLS } from '../voice/prompt';
import { chatActionChannels, voiceToolChannels } from './channels';
import type { ToolChannel } from './channels';

/**
 * One row for every tool Ava has, chat action or voice tool, built from the two registries, so the generated table
 * (docs/tools.md) and the tests that guard it read the real thing. Pure apart from reading the registries.
 */

export interface ToolRow {
  name: string;
  // Where the tool is defined: a chat action, a voice tool, or both under one name
  in: 'chat' | 'voice' | 'both';
  // The group it is listed under in "what can you do?"; undefined when the tool has none (the test fails)
  group: CapabilityGroupId | undefined;
  channels: ToolChannel[];
  // Characters of the tool's definition as the model sees it, for the chat action and the voice tool
  chatChars: number;
  voiceChars: number;
  description: string;
}

const CHANNEL_ORDER: ToolChannel[] = ['panel', 'voice', 'whatsapp', 'agent', 'routine'];

/** Every chat action built the way a chat builds them. Throws when one cannot be built: it is not left out. */
export function builtChatActions(context: AgentContext = {} as AgentContext): Action[] {
  return new ActionBuilder(context, {} as never).buildDefaultActions();
}

/** Plain words for a tool's name: "task_add" becomes "task add". */
export function plainName(name: string): string {
  return name.replace(/_/g, ' ');
}

export function toolInventory(chatActions: Action[] = builtChatActions()): ToolRow[] {
  const rows = new Map<string, ToolRow>();
  const add = (name: string, kind: 'chat' | 'voice', description: string, chars: number, channels: ToolChannel[]) => {
    const existing = rows.get(name);
    const row: ToolRow = existing ?? {
      name,
      in: kind,
      group: TOOL_GROUPS[name],
      channels: [],
      chatChars: 0,
      voiceChars: 0,
      description: shortDescription(description),
    };
    if (existing && existing.in !== kind) row.in = 'both';
    if (kind === 'chat') row.chatChars = chars;
    else row.voiceChars = chars;
    row.channels = CHANNEL_ORDER.filter(channel => row.channels.includes(channel) || channels.includes(channel));
    rows.set(name, row);
  };
  for (const action of chatActions) {
    add(action.name(), 'chat', action.schema.description, action.prompt().length, chatActionChannels(action.name()));
  }
  const voice = [
    ...VOICE_TOOLS.map(tool => ({ name: tool.name, description: tool.description, json: JSON.stringify(tool) })),
    ...registeredVoiceTools().map(({ declaration }) => ({
      name: declaration.name,
      description: declaration.description,
      json: JSON.stringify(declaration),
    })),
  ];
  for (const tool of voice) add(tool.name, 'voice', tool.description, tool.json.length, voiceToolChannels(tool.name));
  return [...rows.values()].sort((a, b) => a.name.localeCompare(b.name));
}

const GROUP_LABEL: Record<CapabilityGroupId, string> = {
  screen: 'Screen and tabs',
  tasks: 'Tasks',
  meetings: 'Meetings and calendar',
  memory: 'Memory and knowledge',
  routines: 'Routines',
  inbox: 'Inbox',
  settings: 'Settings and checks',
  conversation: 'Conversation',
  more: 'More',
};

/** The table written to docs/tools.md. Deterministic: the same tools give the same text. */
export function renderToolTable(rows: ToolRow[]): string {
  const count = (channel: ToolChannel) => rows.filter(row => row.channels.includes(channel)).length;
  const lines = [
    '# Every tool Ava has',
    '',
    'Generated by `src/background/tools/__tests__/inventory.test.ts` from the chat actions and the voice tools as',
    'registered. Do not edit by hand: change a tool, then run',
    '`UPDATE_TOOLS_TABLE=1 pnpm exec vitest run src/background/tools`. The test fails when this file is out of date,',
    'when a tool has no row, or when a tool has no group in `TOOL_GROUPS`. Which channels carry a tool is decided in',
    '`src/background/tools/channels.ts`: WhatsApp, agents and routines are not offered what needs the user at the screen,',
    "and are offered the growth team's tools only when the chat's workspace has a product (the channels below show the",
    'case with a product).',
    '',
    `${rows.length} tools. Per channel: ${(['panel', 'voice', 'whatsapp', 'agent', 'routine'] as ToolChannel[])
      .map(channel => `${channel} ${count(channel)}`)
      .join(', ')}.`,
    '',
    '"In" says where the tool is defined (chat action, voice tool, or both under one name). "Chars" is the size of its',
    'definition as the model sees it: chat / voice. A chat is the panel, WhatsApp, an agent or a routine.',
    '',
    '| Tool | In | Group | Channels | Chars | What it does |',
    '| --- | --- | --- | --- | --- | --- |',
  ];
  for (const row of rows) {
    const chars = [row.chatChars ? String(row.chatChars) : '-', row.voiceChars ? String(row.voiceChars) : '-'];
    const group = row.group ? GROUP_LABEL[row.group] : 'NONE';
    const what = row.description.replace(/\|/g, '\\|');
    lines.push(
      `| \`${row.name}\` (${plainName(row.name)}) | ${row.in} | ${group} | ${row.channels.join(', ')} | ${chars.join(' / ')} | ${what} |`,
    );
  }
  return `${lines.join('\n')}\n`;
}
